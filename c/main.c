#include <stdio.h>          // Подключаем стандартную библиотеку ввода-вывода (нужна для printf)

#ifdef _WIN32               // Если компилируем под Windows...
#include <windows.h>        // ...подключаем заголовок Windows API
#endif                      // Конец условия для Windows

int main(void) {            // Главная функция программы. Отсюда начинается выполнение.
                            // void означает, что функция не принимает аргументов.

#ifdef _WIN32               // Снова проверяем: если это Windows...
    SetConsoleOutputCP(CP_UTF8);  // Устанавливаем кодировку вывода консоли в UTF-8
                                  // (чтобы русские буквы отображались правильно)
    SetConsoleCP(CP_UTF8);        // Устанавливаем кодировку ввода консоли в UTF-8
#endif                      // Конец условия для Windows

    // === Исходные данные студента ===
    const char *student_name_ru = "Малуев Дмитрий Сергеевич";  // ФИО на русском (константный указатель на строку)
    const char *student_name_en = "Maluev Dmitriy Sergeevich";  // ФИО на английском
    int student_number = 11;                                    // Номер студента в списке группы
    const char *group_name = "М3О-110БВк-26";                   // Название группы
    const char *language_name = "C";                            // Название текущего языка

    // Вычисляем контрольное значение: 304 умножить на номер студента
    int control_value = 304 * student_number;                   // Должно получиться 3344

    // === Вывод первой строки (английское приветствие) ===
    // %s — подставить строку, %d — подставить целое число
    printf("Hello to 304 from %s, number %d, group %s!\n",
           student_name_en,     // подставится вместо первого %s
           student_number,      // подставится вместо %d
           group_name);         // подставится вместо второго %s
                                // \n — переход на новую строку

    // === Вывод второй строки (русское приветствие) ===
    printf("Привет, 304! Это %s, номер %d, группа %s!\n",
           student_name_ru,     // русское ФИО
           student_number,      // номер
           group_name);         // группа

    // === Вывод третьей строки (Student ID + Language + Control) ===
    // %02d — вывести число минимум двумя цифрами (с ведущим нулём, если нужно)
    // У тебя номер 11, поэтому будет просто 11
    printf("Student ID: %s/%02d | Language: %s | Control: %d\n",
           group_name,          // группа
           student_number,      // номер (отформатированный)
           language_name,       // язык "C"
           control_value);      // 3344

    return 0;                   // Возвращаем 0 — программа завершилась успешно
}