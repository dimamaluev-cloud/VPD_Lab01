// Объявляем переменную с ФИО студента на русском языке
let student_name_ru = "Малуев Дмитрий Сергеевич"

// Объявляем переменную с ФИО студента на английском языке
let student_name_en = "Maluev Dmitriy Sergeevich"

// Объявляем переменную с номером студента в списке группы
let student_number = 11

// Объявляем переменную с названием учебной группы
let group_name = "М3О-110БВк-26"

// Объявляем переменную с названием используемого языка программирования
let language_name = "F#"

// Задаём код приветствия, который используется в программе
let greeting_code = 304

// Создаём идентификатор студента из названия группы и номера студента
// sprintf позволяет сформировать строку по заданному шаблону
// %s означает, что сюда будет подставлена строка
// %02d означает целое число минимум из двух цифр
let student_id = sprintf "%s/%02d" group_name student_number

// Вычисляем контрольное значение путём умножения кода приветствия на номер студента
let control_value = greeting_code * student_number

// Выводим приветствие на английском языке
// %d используется для целых чисел, а %s — для строк
printfn "Hello to %d from %s, number %d, group %s!"
    greeting_code student_name_en student_number group_name

// Выводим приветствие на русском языке
// Подставляем код приветствия, русское ФИО, номер и название группы
printfn "Привет, %d! Это %s, номер %d, группа %s!"
    greeting_code student_name_ru student_number group_name

// Выводим идентификатор студента, язык программирования и контрольное значение
// %s используется для строк, а %d — для целых чисел
printfn "Student ID: %s | Language: %s | Control: %d"
    student_id language_name control_value

// Начинаем обработку английского ФИО для демонстрации возможностей F#

// Разбиваем английское ФИО на отдельные слова
// Split разделяет строку по пробелам
// RemoveEmptyEntries исключает пустые элементы, если между словами несколько пробелов
let word_lengths =
    student_name_en.Split([|' '|], System.StringSplitOptions.RemoveEmptyEntries)

    // Оператор конвейера |> передаёт полученный массив следующей функции
    // Array.map применяет указанную операцию к каждому элементу массива
    // fun word -> word.Length означает: взять слово и получить количество его символов
    |> Array.map (fun word -> word.Length)

// Вычисляем общую длину всех слов английского ФИО
// Оператор |> передаёт массив функции Array.sum
// Array.sum складывает все числа массива
let total_length = word_lengths |> Array.sum

// Подсчитываем количество слов в английском ФИО
// Array.length возвращает количество элементов массива
let word_count = word_lengths |> Array.length

// Выводим длину каждого отдельного слова
// %A позволяет вывести содержимое массива в удобном для просмотра виде
printfn "Word lengths: %A" word_lengths

// Выводим суммарное количество букв во всех словах
// %d используется для вывода целого числа
printfn "Total letters: %d" total_length

// Выводим количество слов в английском ФИО
printfn "Word count: %d" word_count
